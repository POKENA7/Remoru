import "server-only";

import { cache } from "react";

/**
 * このリクエストの「いま」。**1 リクエストにつき 1 回しか読まない。**
 *
 * 取得関数がそれぞれ `Date.now()` を読むと、同じ画面の中で違う時刻を見る。
 * 日境界をまたいだ瞬間に「復習の一覧」と「未作成の件数」が別々の日で
 * 判定され、噛み合わない数が出る。L07（環境で変わる入力を自分の環境の値だけで
 * 固めない）と同じ種類の欠陥で、手元では滅多に再現しない。
 *
 * `cache()` は引数で鍵を作るので、引数を取らないこの関数はリクエスト内で
 * 1 つの値に固定される。ドメイン層へは、これまでどおり値として渡す。
 */
export const requestNow = cache(() => Date.now());
